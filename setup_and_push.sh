#!/usr/bin/env bash
set -euo pipefail
# Self-contained source archive. No credentials; never executes trading.
mode=push
if [[ "${1:-}" == "--extract-only" ]]; then
  mode=extract
  shift
fi
target="${1:-TradingEOD}"
if [[ $# -gt 1 || -z "$target" ]]; then
  echo 'Usage: bash setup_and_push.sh [--extract-only] [NEW_DIRECTORY]' >&2
  exit 2
fi
script_path="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/$(basename -- "${BASH_SOURCE[0]}")"
if command -v python3 >/dev/null 2>&1 && python3 -c 'import sys; assert sys.version_info >= (3,12)' >/dev/null 2>&1; then
  py=python3
elif command -v python >/dev/null 2>&1 && python -c 'import sys; assert sys.version_info >= (3,12)' >/dev/null 2>&1; then
  py=python
else
  echo 'Python 3.12+ is required.' >&2
  exit 1
fi
"$py" -c 'import sys; assert sys.version_info >= (3,12), "Python 3.12+ required"'
if [[ -e "$target" ]]; then
  echo 'Choose a NEW directory; existing paths are never overwritten.' >&2
  exit 1
fi
if [[ "$mode" == push ]]; then
  command -v git >/dev/null 2>&1 || { echo 'Git is required.' >&2; exit 1; }
  git var GIT_AUTHOR_IDENT >/dev/null
fi
mkdir -p -- "$target"
target="$(cd -- "$target" && pwd)"
if [[ "$mode" == push ]]; then
  git -C "$target" init -b main
  git -C "$target" remote add origin https://github.com/marcoabud/TradingEOD.git
  # Read the remote before mutation; authentication failures abort safely.
  remote_heads="$(git -C "$target" ls-remote --heads origin)"
  if [[ -n "$remote_heads" ]]; then
    if [[ "$remote_heads" != *refs/heads/main* ]]; then
      echo 'Remote has history but no main branch; inspect it before deploying.' >&2
      exit 1
    fi
    git -C "$target" fetch origin main
    git -C "$target" checkout -B main FETCH_HEAD
  fi
fi
